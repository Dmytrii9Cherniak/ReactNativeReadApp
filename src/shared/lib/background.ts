/**
 * Фонова дія, результат якої користувачу не потрібен (сховати заставку, застосувати
 * яскравість). Її збій не має ламати застосунок і не має бути «unhandled rejection».
 * Для дій користувача так не можна — там помилку показуємо (див. useSubmit).
 */
export function runInBackground(task: () => Promise<unknown>): void {
  try {
    task().catch(() => undefined);
  } catch {
    // Синхронна помилка до старту — так само ігноруємо
  }
}
